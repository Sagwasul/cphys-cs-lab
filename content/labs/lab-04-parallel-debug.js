        '    """分块局部累加 + 顺序归约（与 OpenMP reduction 语义等价的确定性版本）。',
        '',
        '    分块边界用 (i * N) // nthreads 计算：它保证各块长度最多相差 1，',
        '    并且当 N 不能被 nthreads 整除时不会漏掉或多算元素。',
        '    局部和按 i 递增的顺序相加，因此结果不依赖任何调度。',
