        '',
        'def build_order(edges):',
        '    """拓扑排序（Kahn 算法 + 最小堆，保证输出确定）。',
        '',
        '    1) 统计每个名字的入度，并记录"依赖 -> 后继"的邻接表；',
        '    2) 把所有入度为 0 的名字放进最小堆（堆顶即字典序最小的可用名字）；',
        '    3) 每次弹出堆顶加入结果，并把它所有后继的入度减 1，减到 0 就入堆；',
        '    4) 若结果长度小于总节点数，说明剩下的节点互相牵制 —— 存在环。',
        '',
        '    复杂度 O((V + E) log V)，这正是 make -j 决定构建顺序所做的计算。',
        '    """',
        '    nodes = set(edges)',
        '    for deps in edges.values():',
        '        nodes.update(deps)',
        '',
        '    indeg = dict.fromkeys(nodes, 0)',
        '    succ = {n: [] for n in nodes}',
        '    for target, deps in edges.items():',
        '        for dep in deps:',
        '            indeg[target] += 1',
        '            succ[dep].append(target)',
        '',
        '    heap = [n for n in nodes if indeg[n] == 0]',
        '    heapq.heapify(heap)',
        '',
        '    order = []',
        '    while heap:',
        '        name = heapq.heappop(heap)        # 字典序最小且已满足依赖',
        '        order.append(name)',
        '        for nxt in succ[name]:',
        '            indeg[nxt] -= 1',
        '            if indeg[nxt] == 0:',
        '                heapq.heappush(heap, nxt)',
        '',
        '    if len(order) != len(nodes):',
        '        raise ValueError("依赖图中存在循环，无法确定构建顺序")',
        '    return order',
        '',
        '',
        'def bisect_steps(n):',
        '    """ceil(log2(n))：每测一次就把候选范围砍一半。',
        '',
